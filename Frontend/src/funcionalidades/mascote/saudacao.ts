export function poseSaudacao(tempoMs: number): PoseCompleta {
  const t = Number.isFinite(tempoMs)
    ? Math.min(DURACAO_SAUDACAO, Math.max(0, tempoMs))
    : 0;
  const base = interpolarRoteiro(quadros, t / DURACAO_SAUDACAO);
  const comFisica = aplicarFisicaSecundaria(base, quadros, t, DURACAO_SAUDACAO);
  return {
    ...comFisica,
    olhos: Math.min(comFisica.olhos, piscarEmInstantes(t, [520, 3120], 80)),
  };
}
