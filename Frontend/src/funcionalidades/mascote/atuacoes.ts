export function poseAtuacao(reacao: Reacao, tempoMs: number): PoseCompleta {
  if (reacao === "saudacao") return poseSaudacao(tempoMs);
  const duracao = DURACOES[reacao];
  const t = Number.isFinite(tempoMs)
    ? Math.max(0, Math.min(duracao, tempoMs))
    : 0;
  const quadros = roteiros[reacao];
  const base = interpolarRoteiro(quadros, t / duracao);
  return aplicarFisicaSecundaria(base, quadros, t, duracao);
}
